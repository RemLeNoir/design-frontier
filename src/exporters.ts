import path from 'node:path';
import type { ExportContext, ExporterName } from './types.js';
import { flattenTokens } from './tokens.js';

function kebab(value: string): string {
  return value.replace(/([a-z0-9])([A-Z])/g, '$1-$2').replace(/[._\s]+/g, '-').toLowerCase();
}

function cssValue(value: unknown): string {
  if (Array.isArray(value)) return `cubic-bezier(${value.join(', ')})`;
  if (value && typeof value === 'object') return JSON.stringify(value);
  return String(value);
}

function cssLines(flat: Record<string, unknown>, prefixToRemove = ''): string[] {
  return Object.entries(flat)
    .filter(([key]) => !key.startsWith('themes.'))
    .map(([key, value]) => {
      const normalized = prefixToRemove && key.startsWith(prefixToRemove) ? key.slice(prefixToRemove.length) : key;
      return `  --df-${kebab(normalized)}: ${cssValue(value)};`;
    });
}

export function exportCss(context: ExportContext): Record<string, string> {
  const flat = flattenTokens(context.tokens);
  const rootLines = cssLines(flat);
  const light = Object.fromEntries(Object.entries(flat).filter(([key]) => key.startsWith('themes.light.')));
  const dark = Object.fromEntries(Object.entries(flat).filter(([key]) => key.startsWith('themes.dark.')));
  const themeBlock = (selector: string, values: Record<string, unknown>, prefix: string) => Object.keys(values).length
    ? `\n${selector} {\n${cssLines(values, prefix).join('\n')}\n}\n`
    : '';
  const content = `/* Generated by Design Frontier. Do not edit directly. */\n:root {\n${rootLines.join('\n')}\n}\n${themeBlock('[data-theme="light"]', light, 'themes.light.')}${themeBlock('[data-theme="dark"]', dark, 'themes.dark.')}`;
  return { [path.join('.design-frontier', 'generated', 'tokens.css')]: content };
}

export function exportTypeScript(context: ExportContext): Record<string, string> {
  return {
    [path.join('.design-frontier', 'generated', 'tokens.ts')]: `// Generated by Design Frontier. Do not edit directly.\nexport const designTokens = ${JSON.stringify(context.tokens, null, 2)} as const;\n\nexport type DesignTokens = typeof designTokens;\n`
  };
}

export function exportTailwind(context: ExportContext): Record<string, string> {
  const flat = flattenTokens(context.tokens);
  const colors = Object.fromEntries(Object.entries(flat).filter(([key]) => key.startsWith('color.')).map(([key, value]) => [kebab(key.replace(/^color\./, '')), value]));
  const spacing = Object.fromEntries(Object.entries(flat).filter(([key]) => key.startsWith('space.')).map(([key, value]) => [key.replace(/^space\./, ''), value]));
  const radius = Object.fromEntries(Object.entries(flat).filter(([key]) => key.startsWith('radius.')).map(([key, value]) => [key.replace(/^radius\./, ''), value]));
  const content = `// Generated by Design Frontier. Do not edit directly.\n/** @type {import('tailwindcss').Config} */\nexport default {\n  theme: {\n    extend: {\n      colors: ${JSON.stringify(colors, null, 6)},\n      spacing: ${JSON.stringify(spacing, null, 6)},\n      borderRadius: ${JSON.stringify(radius, null, 6)}\n    }\n  }\n};\n`;
  return { [path.join('.design-frontier', 'generated', 'tailwind.preset.mjs')]: content };
}

export function runBuiltInExporter(name: ExporterName, context: ExportContext): Record<string, string> {
  if (name === 'css') return exportCss(context);
  if (name === 'typescript') return exportTypeScript(context);
  return exportTailwind(context);
}
