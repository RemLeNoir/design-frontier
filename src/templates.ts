import type { CatalogReference, Composition, Layer, ProjectInput, ReferenceSelection } from './types.js';
import { flattenTokens } from './tokens.js';

function list(items: string[], empty = '- None declared.'): string {
  return items.length ? items.map((item) => `- ${item}`).join('\n') : empty;
}


function layerRuleDetails(composition: Composition): string {
  const blocks = Object.values(composition.layer_rules).filter(Boolean).map((rules) => {
    if (!rules) return '';
    const componentLines = Object.entries(rules.components).flatMap(([name, items]) => [
      `#### ${name}`,
      '',
      list(items)
    ]).join('\n');
    const metrics = Object.entries(rules.metrics).map(([key, value]) => `- **${key}:** ${value}`).join('\n');
    return `### ${rules.layer}\n\n**Primary:** ${rules.primary ?? 'none'}${rules.secondary ? `  \n**Secondary:** ${rules.secondary}` : ''}\n\n#### Principles\n\n${list(rules.principles)}\n\n#### Required behavior\n\n${list(rules.requirements)}\n\n#### Prohibited behavior\n\n${list(rules.prohibitions)}${metrics ? `\n\n#### Metrics and geometry\n\n${metrics}` : ''}${componentLines ? `\n\n${componentLines}` : ''}`;
  });
  return blocks.length ? blocks.join('\n\n') : '- No layer recipes are available.';
}

function selectedReferenceRows(composition: Composition, references: CatalogReference[]): string {
  const rows = Object.entries(composition.references).map(([layer, selection]) => {
    const primary = references.find((item) => item.id === selection?.primary);
    const secondary = selection?.secondary ? references.find((item) => item.id === selection.secondary) : undefined;
    return `| ${layer} | ${primary?.name ?? selection?.primary} | ${secondary?.name ?? selection?.secondary ?? ''} | ${selection?.weight ?? ''} | ${selection?.source ?? ''} |`;
  });
  return rows.length ? rows.join('\n') : '| None |  |  |  |  |';
}

function referenceDetails(composition: Composition, references: CatalogReference[]): string {
  const ids = new Set<string>();
  for (const selection of Object.values(composition.references)) {
    if (!selection) continue;
    ids.add(selection.primary);
    if (selection.secondary) ids.add(selection.secondary);
  }
  return [...ids].map((id) => {
    const reference = references.find((item) => item.id === id);
    if (!reference) return '';
    return `### ${reference.name}

${reference.summary}

**Allowed influence:** ${Object.keys(reference.covers_layers).join(', ')}

**Boundaries**

${list(reference.boundaries)}

**Evidence**

${reference.evidence.map((item) => `- [${item.title}](${item.url}) (${item.type})`).join('\n')}`;
  }).filter(Boolean).join('\n\n');
}

export function renderDesign(project: ProjectInput, composition: Composition, references: CatalogReference[]): string {
  return `# DESIGN.md

> Generated by Design Frontier. Canonical data lives in \`.design-frontier/\`.

## Product context

- **Product:** ${project.name}
- **Type:** ${project.product_type}
- **Users:** ${project.users ?? 'Not declared'}
- **Surfaces:** ${project.surfaces}
- **Archetype:** ${composition.archetype}
- **Density:** ${project.density}
- **Theme:** ${project.theme}
- **Device priority:** ${project.device_priority}
- **Accessibility:** ${project.accessibility}
- **Locales:** ${project.locales.join(', ')}

## Goals

${list(project.goals ?? [])}

## Design principles

1. Repeated work must remain predictable across pages.
2. References influence declared layers only.
3. Semantic tokens are used before literal visual values.
4. Application and marketing surfaces share brand identity, not density or composition.
5. Accessibility, task completion and existing component behavior take precedence over visual imitation.
6. Every new variant is documented before it becomes part of the system.

## Reference composition

| Layer | Primary | Secondary | Weight | Source |
|---|---|---|---:|---|
${selectedReferenceRows(composition, references)}

Weights resolve conflicts within a layer. They do not represent percentages of a copied visual style.

## Executable layer contract

The following rules are composed from the selected references. They are implementation requirements, not mood-board notes.

${layerRuleDetails(composition)}

## Surface hierarchy

1. Page surface for the main background.
2. Panel surface when containment adds meaning or interaction.
3. Raised surface for menus, popovers and overlays.
4. Status surface for feedback with explicit semantic meaning.

Do not wrap every section in a card. Use headings, spacing and dividers when containment adds no function.

## Tokens

The source of truth is \`.design-frontier/tokens.json\`. Generated code exports live under \`.design-frontier/generated/\`.

Required semantic groups:

- color.surface
- color.text
- color.border
- color.action
- color.status
- space
- size.control
- size.layout
- radius
- typography
- motion

A page may not create a new semantic meaning by assigning a raw color or dimension locally.

## Typography

- Body and heading families come from tokens.
- Monospace is reserved for code, identifiers and machine output.
- Application headings stay compact.
- Marketing display sizes never transfer into tables, forms or operational navigation.
- Long-form text uses the reading-width token.

## Components

### Buttons

- One primary action per local decision area.
- Destructive actions use danger semantics.
- Pill geometry is reserved for chips, filters and compact selectors unless explicitly registered.
- Disabled actions explain the reason when it is not obvious.

### Forms

- Labels remain visible.
- Validation appears next to the affected field or decision.
- User input survives validation failure.
- Help appears before failure when format expectations are not obvious.
- Every interactive control has a visible focus state.

### Tables and lists

- Tables are used when comparison across fields is the main task.
- Lists or cards are used when each item has a dominant action or narrative summary.
- Bulk actions appear only after explicit selection.
- Active filters are visible and resettable.
- Empty states distinguish absent data, filtered data and unavailable data.

### Navigation

- The application shell is not changed by individual pages.
- Current location is visible.
- Frequent actions are not hidden in overflow menus by default.
- Navigation depth follows the information architecture, not a decorative preference.

### Feedback

Every asynchronous workflow defines loading, success, warning, error and empty behavior. Errors identify the affected task and the next available action.

## Responsive behavior

- Preserve task priority before desktop geometry.
- Secondary filters may collapse into a drawer.
- Tables use horizontal scrolling only when column comparison remains necessary.
- Primary actions remain reachable without traversing unrelated content.
- Mobile adaptations follow the declared ${project.device_priority} priority.

## Requirements

${list(composition.requirements)}

## Boundaries

${list(composition.boundaries)}

## Prohibited patterns

${list(composition.prohibitions)}
- Do not create local spacing scales, radii or color semantics.
- Do not introduce a component variant without documenting its use case.
- Do not import landing composition into operational screens.
- Do not copy proprietary assets, source code or exact page compositions from references.

## Selected reference notes

${referenceDetails(composition, references)}

## Review

Use \`DESIGN-CHECKLIST.md\`, then run:

\`npx design-frontier validate .\`

\`npx design-frontier lint .\`
`;
}

export function renderAppDesign(project: ProjectInput, composition: Composition): string {
  return `# APP-DESIGN.md

> Operational interface contract for ${project.name}.

## Objective

Support repeated work with ${project.density} density, stable navigation and explicit system state.

## Shell

- Navigation model: ${project.navigation ?? 'Use the archetype default'}.
- Header height, sidebar width and page padding come from tokens.
- Authenticated pages share one shell.
- A feature cannot create a page-specific shell.
- Secondary navigation appears only where a real hierarchy exists.

## Page anatomy

1. Context: title, scope, status and relevant metadata.
2. Primary action: the next meaningful action for this page.
3. Controls: search, filters, view options and bulk actions.
4. Work area: table, form, document, dashboard or detail view.
5. Feedback: loading, empty, warning, error and success states.

## Dominant patterns

${list(project.dominant_patterns)}

## Density

- Target: ${project.density}.
- Repeated expert workflows may use compact controls.
- Focus visibility and usable targets are not reduced to create density.
- Small amounts of content are not placed inside oversized cards.
- Blank space must support grouping, reading or product communication.

## Component inventory

Before creating a component:

1. Search the existing component directories.
2. Check whether the need is a state, variant or genuinely new component.
3. Register the new behavior in the design-system specification.
4. Use canonical tokens.
5. Add all required states and tests.

## Required states

- hover
- focus-visible
- active or selected
- disabled
- loading
- empty
- error
- warning
- success
- read-only
- insufficient permission
- offline or retry when the product can lose connectivity

## Application prohibitions

${list(composition.prohibitions)}
- No marketing-sized typography in the work area.
- No decorative gradient without a defined information purpose.
- No page-specific navigation model.
- No hidden primary action solely to make the layout look simpler.
`;
}

export function renderLandingDesign(project: ProjectInput, composition: Composition): string {
  return `# LANDING-DESIGN.md

> Public product communication contract for ${project.name}.

## Objective

Explain the product to the intended audience, show credible evidence and move qualified visitors toward one clear next action.

## Narrative order

1. What the product does and for whom.
2. Visible evidence of the product or workflow.
3. Capabilities grouped by user problem.
4. Proof, trust and objections.
5. Conversion action with a clear expectation.

## Visual rhythm

- Public pages may use more whitespace and larger type than the application.
- Large sections require real content, product evidence or a narrative transition.
- Brand expression cannot reduce comprehension, accessibility or performance.
- Motion is optional and never required to understand the message.

## Product evidence

- Prefer real interface crops, diagrams, examples or concrete outputs.
- Decorative mockups cannot be the only proof.
- Screenshots reflect the current product and the application design contract.
- Product images use consistent framing, crop rules and captions.

## Calls to action

- Use one primary CTA label consistently.
- Explain what happens after activation when the commitment is not obvious.
- Secondary CTAs do not compete equally with the primary path.
- Conversion components define success, error and loading states.

## Boundaries

${list(composition.boundaries)}
- Display type, public spacing and animation do not redefine application screens.
- References do not authorize copying proprietary assets or exact sections.
`;
}

